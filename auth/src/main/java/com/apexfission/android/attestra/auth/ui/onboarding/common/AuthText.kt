/** Resolves library-owned controller messages without changing public String state APIs.
 * Unknown service/host text is passed through unchanged; resources follow host configuration.
 */
@Composable
internal fun authText(text: String): String {
    val context = LocalContext.current
    val configuration = LocalConfiguration.current
    val messages = remember(context, configuration) { AuthMessages(context) }
    return messages.localize(text)
}

internal class AuthMessages(context: Context) {
    private val resources = context.resources
    private val english = context.createConfigurationContext(
        Configuration(resources.configuration).apply { setLocale(Locale.ENGLISH) }
    ).resources
    private val templates = ids.map { id ->
        val value = english.getString(id)
        val parts = value.split(Regex("%[1-9][0-9]*" + Regex.escape("$") + "s"))
        val pattern = parts.joinToString("(.*?)") { Regex.escape(it) }
        Triple(id, value, if (parts.size > 1) Regex("^" + pattern + "$", RegexOption.DOT_MATCHES_ALL) else null)
    }

    internal fun localize(text: String): String {
        templates.firstOrNull { it.second == text }?.let { return resources.getString(it.first) }
        for ((id, _, pattern) in templates) {
            val match = pattern?.matchEntire(text) ?: continue
            val arguments = match.groupValues.drop(1).map { localize(it) }.toTypedArray()
            return resources.getString(id, *arguments)
        }
        return text
    }

